"""Rate cards, time-of-day tariffs and the bundled price catalog.

The static ``pricing.py`` table cannot answer "what does *this* provider charge
for *this* model *right now*". This module resolves that question from a
compact catalog generated by ``scripts/build_llm_price_catalog.py``:

- ``providers``: exact provider/model prices from models.dev (USD per 1M);
- ``offers``: cross-provider min/median/max per model, used as a conservative
  upper bound when the user routes through an unknown relay;
- ``tariffs``: UTC time-of-day windows parsed from OpenRouter's
  ``pricing.overrides`` (e.g. DeepSeek peak = 2x);
- ``tiers``: long-context price tiers (``min_prompt_tokens``);
- ``aliases``: route/model IDs that map onto a canonical model.

Ambiguous data is never treated as free: ``0`` / missing prices are excluded at
generation time, and an unknown lookup returns ``None`` so the caller can fall
back to the static table with a visible low-confidence marker.
"""

from __future__ import annotations

import json
import logging
import re
from collections.abc import Callable, Iterable, Mapping
from contextlib import suppress
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from openbiliclaw.llm.pricing import CACHE_HIT_DISCOUNT

logger = logging.getLogger(__name__)

_BUNDLED_PATH = Path(__file__).with_name("pricing_catalog.json")

_PROVIDER_ALIASES = {
    "claude": "anthropic",
    "gemini": "google",
    "zhipu": "zai",
    "zhipuai": "zai",
    "glm": "zai",
}

# Providers that are not expected to have an exact card; their prices come
# from the model-level offer distribution or a user override.
_RELAY_PROVIDERS = frozenset(
    {
        "openai_compatible",
        "openrouter",
        "orcarouter",
        "requesty",
        "api_route",
        "cheaperinference",
    }
)

_DATE_SUFFIX = re.compile(r"[-_](?:20\d{2}[-_]?\d{2}[-_]?\d{2}|\d{4})$")
_VARIANT_SUFFIX = re.compile(r"(?::(?:batch|free|thinking|extended|latest))+$")


def normalize_model_id(raw: str) -> str:
    """Canonicalize a model ID for catalog lookup.

    Drops the vendor prefix (``deepseek/``), ``:batch``-style variants, and a
    trailing release date. The same function is used by the catalog builder,
    so a generated key and a runtime lookup agree.
    """

    value = str(raw or "").strip().lower()
    if "/" in value:
        value = value.rsplit("/", 1)[-1]
    value = _VARIANT_SUFFIX.sub("", value)
    value = _DATE_SUFFIX.sub("", value)
    return value


@dataclass(frozen=True)
class TokenRates:
    """Prices in ``currency`` per 1,000,000 tokens."""

    input_per_mtok: float
    output_per_mtok: float
    cache_read_per_mtok: float | None = None
    cache_write_per_mtok: float | None = None


@dataclass(frozen=True)
class RateTier:
    """A long-context price tier that applies at/above ``min_prompt_tokens``."""

    min_prompt_tokens: int
    rates: TokenRates


@dataclass(frozen=True)
class TariffWindow:
    """A UTC time-of-day price window (weekday-scoped, wrap-aware)."""

    days: frozenset[int]  # 0=Monday .. 6=Sunday; empty = every day
    start_minute: int  # inclusive, minutes since midnight UTC
    end_minute: int  # exclusive; 0 with start>0 means "until midnight"
    rates: TokenRates
    label: str = "peak"
    multiplier: float = 1.0
    source: str = ""

    def matches(self, moment: datetime) -> bool:
        minute = moment.hour * 60 + moment.minute
        if self.start_minute < self.end_minute:
            if self.days and moment.weekday() not in self.days:
                return False
            return self.start_minute <= minute < self.end_minute
        if self.start_minute > self.end_minute:
            # Wraps midnight. The after-midnight half belongs to the previous
            # day's window (a Friday 23:00-01:00 window applies to Saturday
            # 00:30), so check the day on the correct side of the boundary.
            if minute >= self.start_minute:
                weekday = moment.weekday()
            else:
                weekday = (moment.weekday() - 1) % 7
            if self.days and weekday not in self.days:
                return False
            return minute >= self.start_minute or minute < self.end_minute
        return False

    def end_at(self, moment: datetime) -> datetime:
        """Return the next boundary at which this window stops matching."""

        day_start = moment.replace(hour=0, minute=0, second=0, microsecond=0)
        candidate = day_start + timedelta(minutes=self.end_minute)
        if candidate <= moment:
            # The end already passed today (wrapped or post-window); the next
            # matching end is tomorrow's boundary.
            candidate += timedelta(days=1)
        return candidate


@dataclass(frozen=True)
class RateCard:
    """Resolved prices for one provider/model pair."""

    provider: str
    model: str
    rates: TokenRates
    currency: str = "USD"
    source: str = ""
    confidence: str = "exact"
    tiers: tuple[RateTier, ...] = ()
    tariffs: tuple[TariffWindow, ...] = ()
    verified_at: str = ""

    def current_tariff(self, moment: datetime) -> TariffWindow | None:
        for window in self.tariffs:
            if window.matches(moment):
                return window
        return None

    def effective(
        self,
        *,
        now: datetime | None = None,
        prompt_tokens: int = 0,
        include_next_change: bool = False,
    ) -> EffectiveRate:
        moment = _as_utc(now)
        rates = self.rates
        tier_label = ""
        for tier in self.tiers:
            if prompt_tokens >= tier.min_prompt_tokens:
                rates = tier.rates
                tier_label = f"{tier.min_prompt_tokens}+"
        window = self.current_tariff(moment)
        if window is not None:
            rates = window.rates
        next_change = None
        if include_next_change:
            next_change = self._next_label_change(moment)
        return EffectiveRate(
            provider=self.provider,
            model=self.model,
            rates=rates,
            currency=self.currency,
            source=self.source,
            confidence=self.confidence,
            tariff_label=window.label if window else "base",
            tariff_multiplier=window.multiplier if window else 1.0,
            tier_label=tier_label,
            next_change_at=next_change,
            now=moment,
        )

    def next_off_peak(self, moment: datetime) -> datetime | None:
        """Return when the current peak window ends, or None when not peak."""

        window = self.current_tariff(moment)
        if window is None or window.label != "peak":
            return None
        return window.end_at(moment)

    def _next_label_change(self, moment: datetime) -> datetime | None:
        current = self.current_tariff(moment)
        current_label = current.label if current else "base"
        # Windows are minute-granular and hour-aligned in every catalog we
        # generate today; a bounded hourly scan is cheap and avoids a
        # per-call loop over 11k minutes.
        for hours in range(1, 8 * 24):
            candidate = moment + timedelta(hours=hours)
            window = self.current_tariff(candidate)
            if (window.label if window else "base") != current_label:
                return candidate
        return None


@dataclass(frozen=True)
class EffectiveRate:
    """A card evaluated at a specific time and prompt size."""

    provider: str
    model: str
    rates: TokenRates
    currency: str
    source: str
    confidence: str
    tariff_label: str
    tariff_multiplier: float
    tier_label: str
    next_change_at: datetime | None
    now: datetime

    def cost(
        self,
        *,
        prompt_tokens: int,
        completion_tokens: int,
        cached_tokens: int = 0,
        usd_cny: float = 7.2,
    ) -> float:
        """Return the estimated cost in CNY for one call.

        ``cached_tokens`` is billed at the explicit ``cache_read`` price when
        the catalog has one; otherwise the provider's cache discount is applied
        to the input rate. Never credits a discount the catalog did not state
        beyond that.
        """

        prompt = max(0, int(prompt_tokens))
        completion = max(0, int(completion_tokens))
        cached = max(0, min(int(cached_tokens), prompt))
        non_cached = prompt - cached
        cache_rate = self.rates.cache_read_per_mtok
        if cache_rate is None and cached:
            discount = CACHE_HIT_DISCOUNT.get(self.provider, 0.5)
            cache_rate = self.rates.input_per_mtok * discount
        raw = (
            (non_cached / 1_000_000.0) * self.rates.input_per_mtok
            + (cached / 1_000_000.0) * (cache_rate or 0.0)
            + (completion / 1_000_000.0) * self.rates.output_per_mtok
        )
        if self.currency.upper() == "USD":
            raw *= float(usd_cny)
        return round(raw, 8)


def _as_utc(moment: datetime | None) -> datetime:
    if moment is None:
        return datetime.now(UTC)
    if moment.tzinfo is None:
        return moment.replace(tzinfo=UTC)
    return moment.astimezone(UTC)


def _rates_from_mapping(
    raw: Mapping[str, Any],
    *,
    allow_zero: bool = False,
) -> TokenRates | None:
    try:
        input_rate = float(raw["input"])
        output_rate = float(raw["output"])
    except (KeyError, TypeError, ValueError):
        return None
    if input_rate < 0 or output_rate < 0:
        return None
    if not allow_zero and (input_rate <= 0 or output_rate <= 0):
        # A catalog card must be a real paid rate. A zero here is a missing
        # or sentinel value (sensenova lists deepseek-v4-flash at 0), and
        # treating it as free would silently disable the spend cap.
        return None
    cache_read = raw.get("cache_read")
    cache_write = raw.get("cache_write")
    return TokenRates(
        input_per_mtok=input_rate,
        output_per_mtok=output_rate,
        cache_read_per_mtok=float(cache_read) if cache_read is not None else None,
        cache_write_per_mtok=float(cache_write) if cache_write is not None else None,
    )


def _tariff_from_mapping(raw: Mapping[str, Any], *, source: str) -> TariffWindow | None:
    rates = _rates_from_mapping(raw)
    if rates is None:
        return None
    try:
        start = int(raw["start"])
        end = int(raw["end"])
    except (KeyError, TypeError, ValueError):
        return None
    if not (0 <= start < 1440 and 0 <= end <= 1440) or start == end:
        return None
    days_raw = raw.get("days")
    days = frozenset(int(day) for day in days_raw) if isinstance(days_raw, list) else frozenset()
    return TariffWindow(
        days=days,
        start_minute=start,
        end_minute=end,
        rates=rates,
        label=str(raw.get("label") or "peak"),
        multiplier=float(raw.get("multiplier") or 1.0),
        source=source,
    )


class RateCatalog:
    """Lookup layer over the generated catalog plus optional user overrides."""

    def __init__(
        self,
        data: Mapping[str, Any],
        *,
        overrides: Iterable[Any] = (),
        source_path: Path | None = None,
    ) -> None:
        self._data = dict(data)
        self._source_path = source_path
        self._providers: dict[str, dict[str, Mapping[str, Any]]] = {}
        for provider, payload in (data.get("providers") or {}).items():
            if isinstance(payload, dict) and isinstance(payload.get("models"), dict):
                self._providers[str(provider).lower()] = payload["models"]
        self._offers: dict[str, Mapping[str, Any]] = {
            str(model).lower(): payload
            for model, payload in (data.get("offers") or {}).items()
            if isinstance(payload, dict)
        }
        self._aliases: dict[str, str] = {
            str(key).lower(): str(value).lower()
            for key, value in (data.get("aliases") or {}).items()
        }
        # Tariffs/tiers are provider-specific. A model id alone is not enough:
        # a relay or another vendor may resell the same model on a flat price,
        # and a user override must never inherit the catalog's window.
        self._tariffs: dict[tuple[str, str], tuple[TariffWindow, ...]] = {}
        tariff_groups: dict[tuple[str, str], list[TariffWindow]] = {}
        for model, windows in (data.get("tariffs") or {}).items():
            if not isinstance(windows, list):
                continue
            model_key = str(model).lower()
            for raw in windows:
                if not isinstance(raw, dict):
                    continue
                window = _tariff_from_mapping(raw, source="openrouter")
                if window is None:
                    continue
                provider = str(raw.get("provider") or "").strip().lower()
                tariff_groups.setdefault((provider, model_key), []).append(window)
                if provider and provider != "openrouter":
                    tariff_groups.setdefault(("openrouter", model_key), []).append(window)
        for key, windows in tariff_groups.items():
            self._tariffs[key] = tuple(windows)

        self._tiers: dict[tuple[str, str], tuple[RateTier, ...]] = {}
        tier_groups: dict[tuple[str, str], list[RateTier]] = {}
        for model, tiers in (data.get("tiers") or {}).items():
            if not isinstance(tiers, list):
                continue
            model_key = str(model).lower()
            for raw in tiers:
                if not isinstance(raw, dict):
                    continue
                rates = _rates_from_mapping(raw)
                threshold_raw = raw.get("min_prompt_tokens")
                if not isinstance(threshold_raw, int | float | str):
                    continue
                try:
                    threshold = int(threshold_raw)
                except (TypeError, ValueError):
                    continue
                if rates is None or threshold <= 0:
                    continue
                provider = str(raw.get("provider") or "").strip().lower()
                tier = RateTier(min_prompt_tokens=threshold, rates=rates)
                tier_groups.setdefault((provider, model_key), []).append(tier)
                if provider and provider != "openrouter":
                    tier_groups.setdefault(("openrouter", model_key), []).append(tier)
        for key, parsed_tiers in tier_groups.items():
            self._tiers[key] = tuple(sorted(parsed_tiers, key=lambda tier: tier.min_prompt_tokens))
        self._override_cards: dict[tuple[str, str], RateCard] = {}
        self._install_overrides(overrides)

        fx = data.get("fx") or {}
        try:
            self._usd_cny = float(fx.get("usd_cny") or 7.2)
        except (TypeError, ValueError):
            self._usd_cny = 7.2

    # -- construction -------------------------------------------------

    @classmethod
    def load(
        cls,
        path: str | Path | None = None,
        *,
        overrides: Iterable[Any] = (),
    ) -> RateCatalog:
        """Load the bundled catalog (or an explicit path) without raising.

        A missing or corrupt catalog returns an empty catalog: price lookup
        falls back to the static table and the UI shows a low-confidence
        warning. It must never prevent the runtime from starting.
        """

        catalog_path = Path(path) if path is not None else _BUNDLED_PATH
        try:
            data = json.loads(catalog_path.read_text(encoding="utf-8"))
            if not isinstance(data, dict):
                raise ValueError("catalog root must be an object")
        except (OSError, ValueError):
            logger.warning("LLM price catalog unavailable at %s", catalog_path, exc_info=True)
            data = {}
        return cls(data, overrides=overrides, source_path=catalog_path)

    @classmethod
    def from_dict(
        cls,
        data: Mapping[str, Any],
        *,
        overrides: Iterable[Any] = (),
    ) -> RateCatalog:
        return cls(data, overrides=overrides)

    @property
    def usd_cny(self) -> float:
        return self._usd_cny

    def set_usd_cny(self, rate: float) -> None:
        """Apply a configured FX rate to this process-local catalog."""

        if rate > 0:
            self._usd_cny = float(rate)

    @property
    def generated_at(self) -> str:
        return str(self._data.get("generated_at") or "")

    @property
    def sources(self) -> Mapping[str, Any]:
        sources = self._data.get("sources")
        return sources if isinstance(sources, dict) else {}

    @property
    def model_count(self) -> int:
        return len(self._offers)

    @property
    def provider_count(self) -> int:
        return len(self._providers)

    @property
    def source_path(self) -> Path:
        return self._source_path or _BUNDLED_PATH

    # -- lookup -------------------------------------------------------

    def card(
        self,
        provider: str,
        model: str,
        *,
        allow_offers: bool = True,
    ) -> RateCard | None:
        """Return the best card for ``provider/model``.

        Exact provider/model wins; otherwise a model-level offer aggregate is
        returned with ``confidence="derived_relay"``. ``allow_offers=False``
        restricts the lookup to exact cards (used by diagnostics).
        """

        provider_key = _normalize_provider(provider)
        model_key = self._canonical_model(model)
        override = self._override_cards.get((provider_key, model_key))
        if override is not None:
            return override
        models = self._providers.get(provider_key)
        if models:
            record = models.get(str(model).strip().lower()) or models.get(model_key)
            if record is not None:
                return self._card_from_record(provider_key, model_key, record, "exact")
        if not allow_offers or provider_key in {"ollama", "sponsored", "siliconflow_free"}:
            return None
        offer = self._offers.get(model_key)
        if offer is None:
            return None
        rates = TokenRates(
            input_per_mtok=float(offer["input_max"]),
            output_per_mtok=float(offer["output_max"]),
            cache_read_per_mtok=(
                float(offer["cache_read_max"]) if offer.get("cache_read_max") is not None else None
            ),
        )
        return self._build_card(
            provider=provider_key,
            model=model_key,
            rates=rates,
            currency="USD",
            source="models.dev:offers",
            confidence="derived_relay",
            verified_at=self.generated_at,
            catalog_pricing=False,
        )

    def resolve(
        self,
        provider: str,
        model: str,
        *,
        now: datetime | None = None,
        prompt_tokens: int = 0,
        include_next_change: bool = False,
    ) -> EffectiveRate | None:
        card = self.card(provider, model)
        if card is None:
            return None
        return card.effective(
            now=now,
            prompt_tokens=prompt_tokens,
            include_next_change=include_next_change,
        )

    def is_peak(self, provider: str, model: str, *, now: datetime | None = None) -> bool:
        """True only when a *known* tariff window says the current rate is peak.

        Unknown providers/models never defer: pretending a cheap window exists
        would silently starve the daemon.
        """

        effective = self.resolve(provider, model, now=now)
        return bool(effective and effective.tariff_label == "peak")

    def next_off_peak(
        self,
        provider: str,
        model: str,
        *,
        now: datetime | None = None,
    ) -> datetime | None:
        card = self.card(provider, model)
        if card is None:
            return None
        return card.next_off_peak(_as_utc(now))

    # -- internals ----------------------------------------------------

    def _canonical_model(self, model: str) -> str:
        key = str(model or "").strip().lower()
        if key in self._aliases:
            return self._aliases[key]
        normalized = normalize_model_id(key)
        return self._aliases.get(normalized, normalized)

    def _card_from_record(
        self,
        provider: str,
        model: str,
        record: Mapping[str, Any],
        confidence: str,
    ) -> RateCard | None:
        rates = _rates_from_mapping(record)
        if rates is None:
            return None
        return self._build_card(
            provider=provider,
            model=model,
            rates=rates,
            currency=str(record.get("currency") or "USD").upper(),
            source=str(record.get("source") or "models.dev"),
            confidence=confidence,
            verified_at=self.generated_at,
        )

    def _build_card(
        self,
        *,
        provider: str,
        model: str,
        rates: TokenRates,
        currency: str,
        source: str,
        confidence: str,
        verified_at: str,
        catalog_pricing: bool = True,
    ) -> RateCard:
        # Tariffs/tiers come from the catalog only for the provider that
        # published them. Relays and user overrides keep flat rates; a relay
        # can opt into a manual ``peak_hours`` window instead.
        tariffs: tuple[TariffWindow, ...] = ()
        tiers: tuple[RateTier, ...] = ()
        if catalog_pricing:
            tariffs = self._tariffs.get((provider, model), self._tariffs.get(("", model), ()))
            tiers = self._tiers.get((provider, model), self._tiers.get(("", model), ()))
        return RateCard(
            provider=provider,
            model=model,
            rates=rates,
            currency=currency,
            source=source,
            confidence=confidence,
            tiers=tiers,
            tariffs=tariffs,
            verified_at=verified_at,
        )

    def _install_overrides(self, overrides: Iterable[Any]) -> None:
        for override in overrides:
            values = _override_values(override)
            if values is None:
                continue
            provider, model, rates, currency = values
            provider_key = _normalize_provider(provider)
            model_key = self._canonical_model(model)
            self._override_cards[(provider_key, model_key)] = self._build_card(
                provider=provider_key,
                model=model_key,
                rates=rates,
                currency=currency,
                source="user",
                confidence="user",
                verified_at="",
                catalog_pricing=False,
            )


def _normalize_provider(provider: str) -> str:
    key = str(provider or "").strip().lower()
    return _PROVIDER_ALIASES.get(key, key)


def _override_values(
    override: Any,
) -> tuple[str, str, TokenRates, str] | None:
    """Accept either a mapping or an object with the override attributes."""

    def get(name: str) -> Any:
        if isinstance(override, Mapping):
            return override.get(name)
        return getattr(override, name, None)

    provider = str(get("provider") or "").strip()
    model = str(get("model") or "").strip()
    if not provider or not model:
        return None
    try:
        input_rate = float(get("input"))
        output_rate = float(get("output"))
    except (TypeError, ValueError):
        return None
    if input_rate < 0 or output_rate < 0:
        return None
    cache_read = get("cache_read")
    cache_write = get("cache_write")
    return (
        provider,
        model,
        TokenRates(
            input_per_mtok=input_rate,
            output_per_mtok=output_rate,
            cache_read_per_mtok=float(cache_read) if cache_read is not None else None,
            cache_write_per_mtok=float(cache_write) if cache_write is not None else None,
        ),
        str(get("currency") or "USD").upper(),
    )


def catalog_for_runtime(config: object) -> RateCatalog:
    """Build the runtime catalog from a duck-typed config object.

    Reads ``config.llm.pricing`` when present; a missing section or an
    unreadable catalog degrades to the empty catalog (static-table fallback).
    """

    llm = getattr(config, "llm", None)
    pricing = getattr(llm, "pricing", None)
    catalog_path: str | Path | None = (
        str(getattr(pricing, "catalog_path", "") or "").strip() or None
    )
    if catalog_path is None:
        # ``openbiliclaw price --sync`` writes here so a refresh needs no
        # config edit; the bundled snapshot remains the fallback.
        data_path = getattr(config, "data_path", None)
        if data_path is not None:
            candidate = Path(str(data_path)) / "pricing_catalog.json"
            if candidate.is_file():
                catalog_path = candidate
    overrides = getattr(pricing, "overrides", ()) or ()
    catalog = RateCatalog.load(catalog_path, overrides=overrides)
    fx = getattr(pricing, "usd_cny_rate", None)
    if fx:
        with suppress(TypeError, ValueError):
            catalog.set_usd_cny(float(fx))
    return catalog


def primary_route(config: object) -> tuple[str, str]:
    """Return the first configured chat route as ``(provider_type, model)``.

    v2 routing uses ``default_chain[0]`` + ``instances``; legacy configs fall
    back to ``default_provider`` + the matching provider table. Returns
    ``("", "")`` when the route cannot be determined.
    """

    llm = getattr(config, "llm", None)
    chain = getattr(llm, "default_chain", None) or []
    instances = getattr(llm, "instances", None) or {}
    if isinstance(chain, list) and chain:
        instance = instances.get(str(chain[0])) if isinstance(instances, dict) else None
        if instance is not None:
            provider = str(getattr(instance, "provider_type", "") or "").strip()
            model = str(getattr(instance, "model", "") or "").strip()
            if provider and model:
                return provider, model
    provider = str(getattr(llm, "default_provider", "") or "").strip()
    provider_config = getattr(llm, provider, None)
    model = str(getattr(provider_config, "model", "") or "").strip()
    return provider, model


def build_cost_ranker(
    registry: object,
    catalog: RateCatalog,
    *,
    now: datetime | None = None,
) -> Callable[[list[str]], list[str]]:
    """Build a chain ranker that picks the cheapest same-model instance.

    Different models keep their configured order: swapping a flagship for a
    cheap model changes output quality, so the ranker only reorders instances
    that normalize to the same model id. Unknown prices score last (``inf``),
    and a stable sort preserves the original order on ties.
    """

    def rank(order: list[str]) -> list[str]:
        groups: dict[str, list[str]] = {}
        slots: dict[str, list[int]] = {}
        for index, name in enumerate(order):
            route = getattr(registry, "instance_route", None)
            provider_type, model = route(name) if callable(route) else ("", "")
            key = normalize_model_id(model) or f"instance:{name}"
            groups.setdefault(key, []).append(name)
            slots.setdefault(key, []).append(index)

        def score(name: str) -> float:
            route = getattr(registry, "instance_route", None)
            provider_type, model = route(name) if callable(route) else ("", "")
            effective = catalog.resolve(provider_type, model, now=now)
            if effective is None:
                return float("inf")
            native = effective.rates.input_per_mtok + effective.rates.output_per_mtok
            return native * (catalog.usd_cny if effective.currency == "USD" else 1.0)

        # Replace each same-model slot in place. This reorders A1/A2 without
        # moving an unrelated B across the chain: [A1, B, A2] stays [A*, B, A*],
        # preserving the user's cross-model fallback precedence.
        ranked = list(order)
        for key, names in groups.items():
            ordered_names = sorted(names, key=score)
            for slot, name in zip(slots[key], ordered_names, strict=True):
                ranked[slot] = name
        return ranked

    return rank


def peak_predicate_for_config(
    config: object,
    catalog: RateCatalog | None = None,
) -> Callable[[], bool] | None:
    """Build the ``is the primary route in a peak window?`` callable.

    Returns ``None`` when the route or its tariff is unknown: the scheduler
    then falls back to manual ``peak_hours`` or runs normally. Catalog windows
    are evaluated in UTC, so the predicate needs no timezone database.
    """

    active_catalog = catalog if catalog is not None else catalog_for_runtime(config)
    provider, model = primary_route(config)
    if not provider or not model or active_catalog.card(provider, model) is None:
        return None
    return lambda: active_catalog.is_peak(provider, model)
